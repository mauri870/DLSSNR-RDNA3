#!/usr/bin/env python3
# A font file as a C++ header (NR Control's menu font): embed_font.py <font.ttf> <out.hpp> <symbol>
import sys
data = open(sys.argv[1], "rb").read()
sym = sys.argv[3]
with open(sys.argv[2], "w") as f:
    f.write("#pragma once\n// Generated by linux/build/embed_font.py from %s - do not edit.\n" % sys.argv[1].split("/")[-1])
    f.write("inline constexpr unsigned %sSize = %d;\n" % (sym, len(data)))
    f.write("alignas(4) inline const unsigned char %s[] = {\n" % sym)
    for i in range(0, len(data), 24):
        f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
